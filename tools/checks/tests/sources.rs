//! PaperPaw's Rust files: none longer than [`MAX_LINES`] but those listed
//! in `big-files.txt`, which may not grow and leave the list once they are
//! split; none with control characters other than tabs and line ends
//! (write `\0` and the like as escapes).

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    reason = "tests panic on purpose when something is wrong"
)]

use std::collections::BTreeMap;

use paperpaw_checks::{assigned_through_calls, control_characters, lines, root, rust_files};

/// The most lines a Rust file has: split it where it gets longer.
const MAX_LINES: usize = 1500;

/// The files longer than [`MAX_LINES`] from before the limit, each with the
/// most lines it may have.
fn listed() -> BTreeMap<String, usize> {
    include_str!("../big-files.txt")
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(|line| {
            let (count, path) = line.split_once(' ').expect("`<lines> <path>`");
            (
                path.trim().to_string(),
                count.parse().expect("a number of lines"),
            )
        })
        .collect()
}

/// How the first line of a file a tool writes begins ("// Generated by
/// tools/... from ...; do not edit."): such a file has no line limit.
const GENERATED: &[u8] = b"// Generated by ";

/// The tool a generated file's first line names (`tools/...`), if it is
/// there: a file only says it is generated where its tool exists.
fn generator(text: &[u8]) -> Option<String> {
    let rest = text.strip_prefix(GENERATED)?;
    let end = rest
        .iter()
        .position(|b| b.is_ascii_whitespace())
        .unwrap_or(rest.len());
    let tool = std::str::from_utf8(&rest[..end]).ok()?;
    let tool = tool.trim_end_matches([',', ';', ':', '.']);
    (tool.starts_with("tools/") && root().join(tool).is_file()).then(|| tool.to_string())
}

#[test]
fn rust_files_stay_short() {
    let listed = listed();
    let mut wrong = Vec::new();
    let mut seen = Vec::new();
    for (path, file) in rust_files(&root()) {
        let text = std::fs::read(&file).expect("readable");
        // A table a tool writes is not split by hand: no limit.
        if text.starts_with(GENERATED) {
            if generator(&text).is_none() {
                wrong.push(format!(
                    "{path}: its first line says it is generated, but names no tool under tools/ that is there"
                ));
            } else if listed.contains_key(&path) {
                wrong.push(format!(
                    "{path}: generated (its first line says so); take it out of tools/checks/big-files.txt"
                ));
            }
            continue;
        }
        let count = lines(&text);
        match listed.get(&path) {
            Some(&most) if count > most => wrong.push(format!(
                "{path}: {count} lines, more than the {most} it had; split it rather"
            )),
            Some(_) if count <= MAX_LINES => wrong.push(format!(
                "{path}: {count} lines, within the limit now; take it out of tools/checks/big-files.txt"
            )),
            Some(_) => seen.push(path),
            None if count > MAX_LINES => wrong.push(format!(
                "{path}: {count} lines, more than {MAX_LINES}; split it into modules"
            )),
            None => {}
        }
    }
    for path in listed.keys().filter(|p| !seen.contains(p)) {
        if !wrong.iter().any(|w| w.starts_with(path.as_str())) {
            wrong.push(format!(
                "{path}: listed in tools/checks/big-files.txt but gone; take it out"
            ));
        }
    }
    assert!(wrong.is_empty(), "\n{}", wrong.join("\n"));
}

#[test]
fn rust_files_have_no_control_characters() {
    let mut found = Vec::new();
    for (path, file) in rust_files(&root()) {
        for line in control_characters(&std::fs::read(&file).expect("readable")) {
            found.push(format!("{path}:{line}"));
        }
    }
    assert!(
        found.is_empty(),
        "control characters (write them as escapes, e.g. \\0):\n{}",
        found.join("\n")
    );
}

#[test]
fn no_field_of_what_a_call_returned_is_assigned() {
    let mut found = Vec::new();
    for (path, file) in rust_files(&root()) {
        let text = std::fs::read_to_string(&file).expect("readable");
        for (line, method) in assigned_through_calls(&text) {
            found.push(format!("{path}:{line}: `{method}()`"));
        }
    }
    assert!(
        found.is_empty(),
        "a field of what a call returned is assigned, which changes a copy only (a part's \
         area is set with its `set_area`):\n{}",
        found.join("\n")
    );
}
